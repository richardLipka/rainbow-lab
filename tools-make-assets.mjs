/**
 * Regenerates src/assets.js from the official logo files in assets/.
 * Run after replacing a logo:  node tools-make-assets.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';

/** Strip the parts of an Illustrator SVG export that a data: URI never needs. */
function slim(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\r/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

const uri = (svg) => `data:image/svg+xml;base64,${Buffer.from(slim(svg), 'utf8').toString('base64')}`;

const cs = await readFile('assets/fav-logo.svg', 'utf8');
const en = await readFile('assets/fav-logo-en.svg', 'utf8');

const out = `/**
 * assets.js -- binary assets inlined as data: URIs.
 *
 * GENERATED by tools-make-assets.mjs from the files in assets/; edit those
 * and re-run rather than editing this file. Inlined because the built page
 * must run from file:// and inside a strict CSP that blocks every external
 * request, and used through <img src> rather than inline <svg> so the logo's
 * own styles and ids cannot collide with the page's.
 *
 * The FAV marks are the faculty's official ones, taken from
 * https://www.fav.zcu.cz/cs/Faculty/Important-documents/fav-visual-style.html
 */

/** Faculty of Applied Sciences, University of West Bohemia -- per language. */
export const FAV_LOGO = {
  cs: '${uri(cs)}',
  en: '${uri(en)}',
};

/** Intrinsic aspect ratios, so the footer can reserve space before load. */
export const FAV_LOGO_RATIO = { cs: 239.773 / 67.691, en: ${(() => {
  const m = en.match(/viewBox="[\d.\-]+ [\d.\-]+ ([\d.]+) ([\d.]+)"/);
  return m ? `${m[1]} / ${m[2]}` : '239.773 / 67.691';
})()} };
`;

await writeFile('src/assets.js', out);
console.log(`src/assets.js written (cs ${uri(cs).length} B, en ${uri(en).length} B)`);
